import type { Technique, TrainingMode, MartialArt } from '../../types'

const ALL_MODES: TrainingMode[] = [
  'learn', 'coach', 'round', 'reaction', 'custom', 'daily', 'demo',
]

function tech(
  partial: Partial<Technique> &
    Pick<
      Technique,
      | 'id'
      | 'name'
      | 'shortCall'
      | 'category'
      | 'side'
      | 'range'
      | 'difficulty'
      | 'baseExecutionMs'
      | 'recoveryMs'
      | 'recommendedFollowUps'
      | 'incompatibleFollowUps'
      | 'tags'
      | 'coachingCue'
      | 'weightCommit'
    >,
): Technique {
  return {
    martialArts: ['boxing'] as MartialArt[],
    allowedModes: ALL_MODES,
    stanceAgnostic: true,
    requiresEquipment: [],
    leavesGuardOpen: false,
    transitionMs: 90,
    ...partial,
  }
}

