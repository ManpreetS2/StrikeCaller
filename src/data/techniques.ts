export function getTechnique(id: string): Technique {
  const technique = TECHNIQUE_MAP[id]
  if (!technique) {
    throw new Error(`Unknown technique: ${id}`)
  }
  return technique
}

export function getTechniquesByCategory(category: Technique['category']): Technique[] {
  return TECHNIQUES.filter((t) => t.category === category)
}
